-- Account roles used by emails, reviews, and refresh tokens.
DO $$
BEGIN
    CREATE TYPE user_role AS ENUM ('client', 'freelancer');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;


-- Shared email records. Registration and login use this table.
CREATE TABLE IF NOT EXISTS emails (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email VARCHAR(255) NOT NULL UNIQUE,
    role user_role NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- Client accounts.
CREATE TABLE IF NOT EXISTS clients (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username VARCHAR(50) NOT NULL UNIQUE,
    email_id UUID NOT NULL UNIQUE REFERENCES emails(id),
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- Freelancer accounts.
CREATE TABLE IF NOT EXISTS freelancers (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username VARCHAR(50) NOT NULL UNIQUE,
    email_id UUID NOT NULL UNIQUE REFERENCES emails(id),
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- Jobs belong to the client who created them.
CREATE TABLE IF NOT EXISTS jobs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    client_id UUID NOT NULL REFERENCES clients(id),
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- Freelancers can apply to jobs.
-- A freelancer can apply to a particular job only once.
CREATE TABLE IF NOT EXISTS applications (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    job_id UUID NOT NULL REFERENCES jobs(id),
    freelancer_id UUID NOT NULL REFERENCES freelancers(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT applications_job_freelancer_unique
        UNIQUE (job_id, freelancer_id)
);


-- The backend uses these two assignment states for validation.
CREATE TABLE IF NOT EXISTS assignment_statuses (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL UNIQUE
);

INSERT INTO assignment_statuses (name)
VALUES ('Assigned'), ('Accepted')
ON CONFLICT (name) DO NOTHING;


-- One selected freelancer can be assigned to each job.
CREATE TABLE IF NOT EXISTS job_assignments (
    job_id UUID PRIMARY KEY REFERENCES jobs(id),
    freelancer_id UUID NOT NULL REFERENCES freelancers(id),
    status_id SMALLINT NOT NULL REFERENCES assignment_statuses(id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- A review is written after a job has an accepted assignment.
-- The reviewer is determined from the job and assignment in the queries.
-- Each side can submit one review per job.
CREATE TABLE IF NOT EXISTS reviews (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    job_id UUID NOT NULL REFERENCES jobs(id),
    reviewer_role user_role NOT NULL,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT reviews_one_per_role_per_job
        UNIQUE (job_id, reviewer_role)
);


-- Refresh-token hashes are stored here; the raw token is returned to the client.
-- account_id has no foreign key because clients and freelancers have separate tables.
CREATE TABLE IF NOT EXISTS refresh_tokens (
    token_hash TEXT PRIMARY KEY,
    account_id UUID NOT NULL,
    role user_role NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    revoked_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS wallet_nonces (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    account_id UUID NOT NULL,
    role user_role NOT NULL,

    nonce TEXT NOT NULL UNIQUE,

    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_wallet_nonces_account
    ON wallet_nonces (account_id, role);

CREATE INDEX IF NOT EXISTS idx_wallet_nonces_expires_at
    ON wallet_nonces (expires_at);


-- Extra indexes for the list and lookup queries used by the API.
CREATE INDEX IF NOT EXISTS idx_jobs_created_at
    ON jobs (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_jobs_client_created_at
    ON jobs (client_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_applications_freelancer_created_at
    ON applications (freelancer_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_job_assignments_freelancer_id
    ON job_assignments (freelancer_id);

CREATE INDEX IF NOT EXISTS idx_refresh_tokens_account_id
    ON refresh_tokens (account_id);

CREATE INDEX IF NOT EXISTS idx_refresh_tokens_expires_at
    ON refresh_tokens (expires_at);